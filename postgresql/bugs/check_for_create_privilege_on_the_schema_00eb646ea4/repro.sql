CREATE ROLE regress_u1;
CREATE SCHEMA sch1 CREATE TABLE sch1.tbl (a INT, b INT);
GRANT USAGE ON SCHEMA sch1 TO regress_u1;
ALTER TABLE sch1.tbl OWNER TO regress_u1;
SET SESSION AUTHORIZATION regress_u1;
CREATE STATISTICS ON a, b FROM sch1.tbl;
RESET SESSION AUTHORIZATION;
DROP SCHEMA sch1 CASCADE;
DROP ROLE regress_u1;
