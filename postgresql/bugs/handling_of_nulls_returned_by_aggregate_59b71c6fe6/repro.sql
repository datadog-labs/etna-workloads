CREATE FUNCTION balkifnull(int8, int8) RETURNS int8 PARALLEL SAFE STRICT LANGUAGE plpgsql AS $$
BEGIN
    IF $1 IS NULL THEN RAISE 'erroneously called with NULL argument'; END IF;
    RETURN NULL;
END$$;
CREATE AGGREGATE balk(BASETYPE = int4, SFUNC = int4_sum(int8, int4), STYPE = int8,
    COMBINEFUNC = balkifnull(int8, int8), "PARALLEL" = SAFE, INITCOND = '0');
