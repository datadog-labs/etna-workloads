CREATE ROLE ru NOSUPERUSER;
CREATE ROLE ru2 NOSUPERUSER;
GRANT CREATE ON DATABASE postgres TO ru, ru2;
GRANT ru2 TO ru;
CREATE SCHEMA s;
CREATE PUBLICATION p FOR TABLES IN SCHEMA s;
ALTER PUBLICATION p OWNER TO ru;
ALTER SCHEMA s OWNER TO ru;
SET ROLE ru;
ALTER PUBLICATION p OWNER TO ru2;
RESET ROLE;
SELECT pubowner::regrole FROM pg_publication WHERE pubname='p';
