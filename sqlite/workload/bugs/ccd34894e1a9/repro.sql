CREATE TABLE t2(c1 INT, c2 REAL);
WITH s(i) AS (SELECT 1 UNION ALL SELECT i+1 FROM s WHERE i<2000)
  INSERT INTO t2 SELECT i*3+(i%2), CASE WHEN i%97=0 THEN 1.0 ELSE 0.0 END FROM s;
SELECT count(*), sum(m), min(m), max(m) FROM
  (SELECT max(c2) OVER (ORDER BY c1 RANGE 1000.0 PRECEDING) AS m FROM t2);
