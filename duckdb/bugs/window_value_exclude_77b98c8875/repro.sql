.mode list
.nullvalue NULL
WITH src(id, v) AS (
	VALUES
	(1, 10),
	(2, 20)
)
SELECT
	id,
	FIRST_VALUE(v ORDER BY v DESC) OVER (
	  ORDER BY id
	  ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING
	  EXCLUDE CURRENT ROW
	) AS actual
FROM src
ORDER BY id;
WITH src(id, v) AS (
	VALUES
	(1, 10),
	(2, 20)
)
SELECT
	id,
	LAST_VALUE(v ORDER BY v DESC) OVER (
	  ORDER BY id
	  ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING
	  EXCLUDE CURRENT ROW
	) AS actual
FROM src
ORDER BY id;
