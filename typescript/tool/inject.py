"""Make, apply and check injection patches against the base source."""
import filecmp, os, shutil, subprocess, tempfile

import tstree

SCRATCH = os.path.join(tstree.WORK, "scratch")


def changed_impl_files(tree, base=tstree.BASE, roots=("src",)):
    """Implementation files differing between tree and base (symlinks ignored)."""
    out = []
    for root in roots:
        for side, other in ((tree, base), (base, tree)):
            for dp, dns, fns in os.walk(os.path.join(side, root)):
                dns[:] = [d for d in dns if not os.path.islink(os.path.join(dp, d))]
                for fn in fns:
                    p = os.path.join(dp, fn)
                    if os.path.islink(p):
                        continue
                    rel = os.path.relpath(p, side)
                    if is_generated(rel):
                        continue
                    q = os.path.join(other, rel)
                    if not os.path.exists(q) or (side == tree and not filecmp.cmp(p, q, shallow=False)):
                        out.append(rel)
    return sorted(set(out))


def is_generated(rel):
    # Regenerated by every build from diagnosticMessages.json.
    return rel.endswith(("diagnosticInformationMap.generated.ts", "diagnosticMessages.generated.json"))


def make_patch(tree, paths, base=tstree.BASE):
    """Unified git-style patch (a/ b/ prefixes) turning base into tree for paths."""
    os.makedirs(SCRATCH, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=SCRATCH) as td:
        for side, root in (("a", base), ("b", tree)):
            os.makedirs(os.path.join(td, side))
            for rel in paths:
                src = os.path.join(root, rel)
                if os.path.exists(src):
                    dst = os.path.join(td, side, rel)
                    os.makedirs(os.path.dirname(dst), exist_ok=True)
                    shutil.copyfile(src, dst)
        r = subprocess.run(["git", "diff", "--no-index", "--binary", "--src-prefix=", "--dst-prefix=", "a", "b"],
                           cwd=td, capture_output=True)
        if r.returncode not in (0, 1):
            raise RuntimeError(r.stderr.decode())
        return r.stdout


def apply_patch(tree, patch_bytes, reverse=False, fuzz=False):
    """Apply a patch in tree. Returns (ok, method, output)."""
    os.makedirs(SCRATCH, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=SCRATCH, suffix=".patch", delete=False) as tf:
        tf.write(patch_bytes)
    try:
        args = ["git", "apply", "--whitespace=nowarn"] + (["-R"] if reverse else []) + [tf.name]
        r = subprocess.run(args, cwd=tree, capture_output=True)
        if r.returncode == 0:
            return True, "git-apply", r.stderr
        if not fuzz:
            return False, None, r.stderr
        args = ["patch", "-p1", "-F3", "-f", "--no-backup-if-mismatch", "-r", "-"] + (["-R"] if reverse else []) + ["-i", tf.name]
        d = subprocess.run(args + ["--dry-run"], cwd=tree, capture_output=True)
        if d.returncode != 0:
            return False, None, d.stdout + d.stderr
        r = subprocess.run(args, cwd=tree, capture_output=True)
        return r.returncode == 0, "patch-fuzz", r.stdout + r.stderr
    finally:
        os.unlink(tf.name)


def reverse_restores_base(tree, patch_bytes, paths, base=tstree.BASE):
    """Copy tree's touched files aside, reverse the patch there, compare to base."""
    os.makedirs(SCRATCH, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=SCRATCH) as td:
        for rel in paths:
            src = os.path.join(tree, rel)
            if os.path.exists(src):
                os.makedirs(os.path.dirname(os.path.join(td, rel)), exist_ok=True)
                shutil.copyfile(src, os.path.join(td, rel))
        subprocess.run(["git", "init", "-q"], cwd=td, check=True)
        r = subprocess.run(["git", "apply", "-R", "-"], cwd=td, input=patch_bytes, capture_output=True)
        if r.returncode != 0:
            return False
        for rel in paths:
            a, b = os.path.join(base, rel), os.path.join(td, rel)
            if os.path.exists(a) != os.path.exists(b):
                return False
            if os.path.exists(a) and not filecmp.cmp(a, b, shallow=False):
                return False
        return True
