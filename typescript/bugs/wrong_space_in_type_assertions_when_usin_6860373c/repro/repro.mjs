import {createRequire} from 'module';
const ts=createRequire(import.meta.url)(process.env.TYPESCRIPT);
const text='let c = <any[]> [];\nlet d = <string[]> ["e"];\n';
const host={getScriptFileNames:()=>['a.ts'],getScriptVersion:()=>'1',getScriptSnapshot:f=>f==='a.ts'?ts.ScriptSnapshot.fromString(text):undefined,getCurrentDirectory:()=>'/',getCompilationSettings:()=>({}),getDefaultLibFileName:()=>'lib.d.ts',fileExists:f=>f==='a.ts',readFile:f=>f==='a.ts'?text:undefined};
const ls=ts.createLanguageService(host);
const opts={...ts.getDefaultFormatCodeSettings(),insertSpaceAfterTypeAssertion:true};
const edits=ls.getFormattingEditsForDocument('a.ts',opts);
let out=text;
for(const e of [...edits].sort((a,b)=>b.span.start-a.span.start))out=out.slice(0,e.span.start)+e.newText+out.slice(e.span.start+e.span.length);
console.log(out);
