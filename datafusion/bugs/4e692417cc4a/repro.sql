CREATE TABLE t AS SELECT * FROM (VALUES (1,10),(2,20),(3,30),(4,40),(5,50),(6,60)) AS v(id, x);
SELECT LEAD(x, 2) OVER (ORDER BY id ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS l FROM t LIMIT 3;
