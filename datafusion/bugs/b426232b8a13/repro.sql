SELECT COUNT(*) OVER (
  PARTITION BY 1
  ORDER BY cast(1 as decimal(10, 0)) DESC
  RANGE BETWEEN CURRENT ROW AND 1 FOLLOWING
) FROM (SELECT 1);

SELECT a,
       first_value(a) OVER (ORDER BY a ASC RANGE BETWEEN 1 PRECEDING AND 1 FOLLOWING) AS f,
       last_value(a)  OVER (ORDER BY a ASC RANGE BETWEEN 1 PRECEDING AND 1 FOLLOWING) AS l
FROM (
  SELECT CAST(1.50 AS DECIMAL(10,2)) AS a
  UNION ALL SELECT CAST(2.50 AS DECIMAL(10,2))
  UNION ALL SELECT CAST(3.50 AS DECIMAL(10,2))
)
ORDER BY a;
